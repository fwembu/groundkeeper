"""Groundkeeper: compute the tables the firmware needs (the chip has no floating point) -> firmware/src/gk_tables.h

  python3 tools/make_tables.py

Wavetables: one cycle in 512 steps (+1 so the interpolation never wraps), int16. CHOIR and REED have a table per
half octave, because a voice's formants sit at fixed frequencies: the harmonics that fall on them change with the note.
Envelopes are counted in audio blocks: 256 frames at 44.1 kHz, 172.27 a second.
"""
import math
import random
from pathlib import Path

FS = 44100.0
BLOCKS = FS / 256.0
N = 512
BAND0, BAND_STEP, NBAND = 28, 6, 12          # wavetable bands: MIDI 28.. in half octaves (E1 .. C8)


def hz(m):
    return 440.0 * 2.0 ** ((m - 69) / 12.0)


def table(amps, phases=None):
    """one cycle of sum(a_k sin(k x + p_k)), k = 1.. , scaled to a peak of 32000"""
    phases = phases or [0.0] * len(amps)
    w = [sum(a * math.sin((k + 1) * 2 * math.pi * i / N + phases[k]) for k, a in enumerate(amps) if a)
         for i in range(N)]
    pk = max(abs(x) for x in w) or 1.0
    t = [round(x * 32000 / pk) for x in w]
    return t + [t[0]]


def formant_amps(f0, formants, tilt, top=17000.0, extra=lambda f: 1.0):
    """harmonic amplitudes of a source with spectral tilt k^-tilt through resonances (F, bandwidth, gain)"""
    out = []
    k = 1
    while k * f0 < top:
        f = k * f0
        g = sum(a / (1.0 + ((f - F) / B) ** 2) for F, B, a in formants) + 0.015
        out.append(g * extra(f) / k ** tilt)
        k += 1
    return out


def banded(formants, tilt, extra=lambda f: 1.0, seed=1):
    rnd = random.Random(seed)
    tabs = []
    for b in range(NBAND):
        lo = BAND0 + b * BAND_STEP
        f0 = hz(lo + BAND_STEP / 2.0)          # the band's middle
        amps = formant_amps(f0, formants, tilt, top=min(17000.0, 17000.0 * f0 / hz(lo + BAND_STEP)), extra=extra)
        tabs.append(table(amps, [rnd.uniform(0, 2 * math.pi) for _ in amps]))   # (random phases: a softer crest)
    return tabs


def c_array(name, typ, vals, per=16):
    rows = [", ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f"static const {typ} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(rows) + "};\n"


def c_tables(name, tabs):
    body = ",\n".join("    {" + ", ".join(str(v) for v in t) + "}" for t in tabs)
    return f"static const int16_t {name}[{len(tabs)}][{N + 1}] = {{\n{body}}};\n"


def main():
    out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
           "/* Generated by tools/make_tables.py: do not edit. */",
           "#pragma once", "#include <stdint.h>", "",
           f"#define WT_N {N}u", f"#define WT_BAND0 {BAND0}u", f"#define WT_BAND_STEP {BAND_STEP}u",
           f"#define WT_NBAND {NBAND}u", ""]

    # ORGAN: drawbars 8' 4' 2 2/3' 2' 1 3/5' 1' (harmonics 1 2 3 4 5 8), a little 16' in the 2nd
    organ = [0.0] * 8
    for k, a in ((1, 1.0), (2, 0.75), (3, 0.45), (4, 0.5), (5, 0.12), (8, 0.22)):
        organ[k - 1] = a
    out.append("/* ORGAN: harmonics 1 2 3 4 5 8 as drawbars (8' 4' 2 2/3' 2' 1 3/5' 1') */")
    out.append(c_array("ORGAN_WT", "int16_t", table(organ)))

    # CHOIR: an open "ah/oh" (F1 640, F2 1050, F3 2650), a glottal source falling 6 dB an octave
    choir = banded([(640, 90, 1.0), (1050, 110, 0.55), (2650, 170, 0.22), (3400, 250, 0.08)], tilt=1.0, seed=3)
    out.append("/* CHOIR: formants F1 640, F2 1050, F3 2650, F4 3400 Hz over a source falling 6 dB an octave; a table a band */")
    out.append(c_tables("CHOIR_WT", choir))

    # REED: a muted oboe: a weak fundamental, a nasal formant near 1.1 kHz, the top rolled off above 3 kHz
    def muted(f):
        return 1.0 / (1.0 + (f / 3000.0) ** 2)
    reed = banded([(1100, 300, 1.0), (2800, 500, 0.25), (180, 400, 0.25)], tilt=0.5, extra=muted, seed=5)
    out.append("/* REED (a muted oboe): a formant near 1.1 kHz (and 2.8 kHz), a weak fundamental, rolled off above 3 kHz */")
    out.append(c_tables("REED_WT", reed))

    # envelopes, per block. ATTACK: linear to full in T s. RELEASE: exponential, -60 dB in T s.
    att = [0.02, 0.05, 0.1, 0.2, 0.35, 0.5, 0.75, 1.0, 1.5, 2.0, 3.0, 4.0, 6.0, 8.0]
    rel = [0.1, 0.2, 0.35, 0.5, 0.75, 1.0, 1.5, 2.0, 3.0, 4.0, 6.0, 8.0, 12.0, 16.0]
    out.append("/* ATTACK: the level's rise a block (Q15), linear to full in the time shown */")
    out.append(c_array("ATT_INC", "uint16_t", [min(32767, round(32767 / (t * BLOCKS))) for t in att]))
    out.append("static const char *const ATT_LABEL[%d] = {%s};\n" % (len(att), ", ".join(
        f'"{(str(round(t * 1000)) + "ms") if t < 1 else (str(t).rstrip("0").rstrip(".") + "s")}"' for t in att)))
    out.append("/* RELEASE: the share of the level lost a block (Q15), -60 dB in the time shown */")
    out.append(c_array("REL_K", "uint16_t", [round(32768 * (1 - 10 ** (-3 / (t * BLOCKS)))) for t in rel]))
    out.append("static const char *const REL_LABEL[%d] = {%s};\n" % (len(rel), ", ".join(
        f'"{(str(round(t * 1000)) + "ms") if t < 1 else (str(t).rstrip("0").rstrip(".") + "s")}"' for t in rel)))

    # HISS: the noise's gain (Q15) for an RMS of -66 .. -24 dBFS (the noise itself: uniform, RMS 0.577 of full scale)
    hiss = [0] + [round(32768 * 10 ** ((-66 + (i - 1) * 42 / 19) / 20) / 0.577) for i in range(1, 21)]
    out.append("/* HISS: noise gain (Q15): off, then an RMS of -66 .. -24 dBFS in 20 steps */")
    out.append(c_array("HISS_G", "uint16_t", hiss))

    # TONE: -5 .. +5. Below 0 a one-pole low-pass (dark), 0 white, above 0 a one-pole high-pass (bright), each with the
    # gain that keeps the RMS (measured on 200 000 samples of the same noise)
    rnd = random.Random(7)
    noise = [rnd.uniform(-1, 1) for _ in range(200000)]
    rms0 = math.sqrt(sum(x * x for x in noise) / len(noise))
    fcs = [150, 300, 600, 1200, 2400, None, 400, 1000, 2000, 4000, 7000]
    coef, comp = [], []
    for i, fc in enumerate(fcs):
        if fc is None:
            coef.append(0); comp.append(32768); continue
        a = 1 - math.exp(-2 * math.pi * fc / FS)
        lp, acc = 0.0, 0.0
        for x in noise:
            lp += (x - lp) * a
            y = lp if i < 5 else x - lp
            acc += y * y
        coef.append(round(a * 32768)); comp.append(round(32768 * rms0 / math.sqrt(acc / len(noise))))
    out.append("/* TONE: one-pole coefficient (Q15) and RMS-keeping gain (Q15) for -5 .. -1 (low-pass 150 Hz .. 2.4 kHz),"
               " 0 (white), +1 .. +5 (high-pass 400 Hz .. 7 kHz) */")
    out.append(c_array("TONE_A", "uint16_t", coef))
    out.append(c_array("TONE_COMP", "uint32_t", comp))

    # CRACKLE: crackles a second -> a threshold on a 32-bit random number a sample
    rate = [0, 0.3, 0.6, 1, 1.5, 2, 3, 4, 5, 6, 8, 10, 12, 15, 18, 22, 27, 33, 40, 50, 60]
    out.append("/* CRACKLE: 0 .. 60 crackles a second, as a threshold on a 32-bit random number each sample */")
    out.append(c_array("CRK_T", "uint32_t", [round(r * 2 ** 32 / FS) for r in rate]))

    # WOBBLE: the depth of the tape wow (Q16 of the pitch): 0 .. 0.6 % (about 10 cents)
    out.append("/* WOBBLE: the pitch's deviation (Q16): 0 .. 0.6 % (about 10 cents) in 10 steps */")
    out.append(c_array("WOB_D", "uint16_t", [round(65536 * 0.006 * (i / 10) ** 1.5) for i in range(11)]))

    Path("firmware/src/gk_tables.h").write_text("\n".join(out))
    print("firmware/src/gk_tables.h:", sum(len(x) for x in out) // 1024, "KB of source")


if __name__ == "__main__":
    main()
